// Generates src/app/theme-dark.css from Tailwind's own palette.
// Run: node scripts/gen-dark-theme.mjs   (re-run after upgrading Tailwind)
//
// How dark mode works: every Tailwind colour is a CSS variable, so dark mode
// swaps the variables instead of adding dark: classes everywhere.
// - slate (neutrals) is mirrored fully: 50<->950, 100<->900 ... 500 -> 400
//   (so text-slate-900 turns light, bg-slate-50 turns dark).
// - accent colours swap only their light/dark ends (50..300 <-> 950..700) and keep
//   400..600, so solid buttons and badges keep their colour with white text.
// - Areas that are dark in both themes (admin sidebar, dark hero panels,
//   brand gradients) keep the light-theme values: .theme-lock, .bg-mesh-dark,
//   .bg-brand-gradient.
import { readFileSync, writeFileSync } from "node:fs";

const theme = readFileSync(new URL("../node_modules/tailwindcss/theme.css", import.meta.url), "utf8");
const FAMILIES = ["slate", "red", "orange", "amber", "lime", "green", "emerald", "teal", "sky", "blue", "indigo", "violet", "fuchsia", "pink", "rose"];
const SHADES = ["50", "100", "200", "300", "400", "500", "600", "700", "800", "900", "950"];
const val = (f, s) => {
  const m = theme.match(new RegExp(`--color-${f}-${s}:\\s*([^;]+);`));
  if (!m) throw new Error(`missing ${f}-${s}`);
  return m[1].trim();
};
const FULL = { 50: "950", 100: "900", 200: "800", 300: "700", 400: "600", 500: "400", 600: "400", 700: "300", 800: "200", 900: "100", 950: "50" };
const ENDS = { 50: "950", 100: "900", 200: "800", 300: "700", 700: "300", 800: "200", 900: "100", 950: "50" };

const dark = [];
const lock = [];
for (const f of FAMILIES) {
  const map = f === "slate" ? FULL : ENDS;
  for (const s of SHADES) {
    lock.push(`--color-${f}-${s}:${val(f, s)}`);
    if (map[s]) dark.push(`--color-${f}-${s}:${val(f, map[s])}`);
  }
}
const surface = val("slate", "900");
const raised = val("slate", "800");

const LOCK = ':root[data-theme="dark"] :is(.theme-lock,.bg-mesh-dark,.bg-brand-gradient)';
const css = `/* GENERATED by scripts/gen-dark-theme.mjs. Do not edit by hand. */
:root[data-theme="dark"]{color-scheme:dark;--surface:${surface};--surface-raised:${raised};${dark.join(";")}}
${LOCK}{color-scheme:light;${lock.join(";")}}
/* White surfaces become dark surfaces (text-white stays white). */
:root[data-theme="dark"] .bg-white{background-color:var(--surface)}
:root[data-theme="dark"] .bg-white\\/80,:root[data-theme="dark"] .bg-white\\/85,:root[data-theme="dark"] .bg-white\\/95{background-color:color-mix(in oklab,var(--surface) 90%,transparent)}
:root[data-theme="dark"] .via-white{--tw-gradient-via:var(--surface)}
:root[data-theme="dark"] .to-white{--tw-gradient-to:var(--surface)}
:root[data-theme="dark"] .ring-white{--tw-ring-color:var(--surface)}
${LOCK} .bg-white{background-color:#fff}
`;
writeFileSync(new URL("../src/app/theme-dark.css", import.meta.url), css);
console.log(`wrote src/app/theme-dark.css (${css.length} bytes)`);
